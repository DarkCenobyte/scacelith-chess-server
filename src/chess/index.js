/**
 * @param {number} sq 0..63
 * @returns {string} "e4", "-" when out of range.
 */
export function squareName(sq) {
    return (sq | 0) === sq && sq >= 0 && sq < 64 ? SQ_NAMES[sq] : '-';
}

/**
 * @param {string} s "e4" (file letter may be upper case)
 * @returns {number} 0..63, or -1.
 */
export function parseSquare(s) {
    return typeof s === 'string' ? _parseSquare(s) : -1;
}

#!/usr/bin/env node
// Generates `.env.example` and `docs/CONFIG.md` from the configuration table of src/config.js
// (the single source of truth). Run it after adding or changing a key:
//
//   npm run gen:env              writes both files
//   node tools/gen-env-example.js --check    exits 1 when a file is out of date (CI)
//
// .env.example: one block per section; each key is preceded by its description, its type and
// bounds. Keys with a default are commented out with that default (uncomment to change it, so
// that a later release's better default is not pinned by accident); required keys are
// uncommented and empty; secrets never carry a value.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CONFIG_KEYS } from '../src/config.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const SECTION_TITLES = {
    server: 'Server identity and network',
    tls: 'TLS',
    storage: 'Storage',
    secrets: 'Secrets',
    accounts: 'Accounts',
    mail: 'Mail',
    sso: 'Google single sign-on',
    limits: 'Abuse protection and limits',
    games: 'Games',
    matchmaking: 'Matchmaking and ratings',
    anticheat: 'Anti-cheat and sanctions',
    gif: 'Animated GIFs of games',
    observability: 'Observability',
};

const titleOf = (s) => SECTION_TITLES[s] || s.charAt(0).toUpperCase() + s.slice(1);

/** Keys grouped by section, in table order. */
function sections(keys) {
    const out = new Map();
    for (const k of keys) {
        if (!out.has(k.section)) out.set(k.section, []);
        out.get(k.section).push(k);
    }
    return out;
}

function wrap(text, width, prefix) {
    const lines = [];
    let line = '';
    for (const word of String(text).split(/\s+/).filter(Boolean)) {
        if (line && prefix.length + line.length + 1 + word.length > width) { lines.push(prefix + line); line = word; } else line = line ? `${line} ${word}` : word;
    }
    if (line) lines.push(prefix + line);
    return lines;
}

function defaultText(k) {
    if (k.default === undefined || k.default === null) return '';
    if (typeof k.default === 'boolean') return k.default ? 'true' : 'false';
    return String(k.default);
}

function typeText(k) {
    switch (k.type) {
        case 'enum': return `one of ${k.values.join(', ')}`;
        case 'bool': return 'boolean (true/false, 1/0, yes/no, on/off)';
        case 'port': return 'port (0-65535)';
        case 'list': return 'comma-separated list';
        case 'secret': return `secret${k.minBytes ? ` (at least ${k.minBytes} bytes, hex or base64)` : ''}`;
        case 'int': {
            if (k.min !== undefined && k.max !== undefined) return `integer (${k.min}-${k.max})`;
            if (k.min !== undefined) return `integer (>= ${k.min})`;
            if (k.max !== undefined) return `integer (<= ${k.max})`;
            return 'integer';
        }
        case 'number': {
            if (k.min !== undefined && k.max !== undefined) return `number (${k.min}-${k.max})`;
            if (k.min !== undefined) return `number (>= ${k.min})`;
            if (k.max !== undefined) return `number (<= ${k.max})`;
            return 'number';
        }
        case 'string': return k.max ? `text (at most ${k.max} characters)` : 'text';
        case 'path': return 'path (relative to the working directory)';
        default: return k.type;
    }
}

const isSecret = (k) => k.type === 'secret';
const takesFile = (k) => k.type === 'secret';

/** @returns {string} the .env.example text */
export function renderEnvExample(keys = CONFIG_KEYS) {
    const out = [];
    out.push('# Scacelith dedicated server configuration.');
    out.push('#');
    out.push('# Generated by tools/gen-env-example.js from src/config.js: do not edit by hand, run `npm run gen:env`.');
    out.push('# Copy this file to .env (next to package.json, or point SCACELITH_ENV_FILE at it) and adjust it;');
    out.push('# real environment variables take precedence over the file. Check the result with');
    out.push('# `node bin/scacelith-server.js check-config`.');
    out.push('#');
    out.push('# Commented-out lines show the default. Lines marked REQUIRED must be set. Secrets may also be');
    out.push('# given as a file: FOO_FILE=/run/secrets/foo (keeps them out of the environment listing).');
    out.push('# Generate a secret with `node bin/scacelith-server.js gen-secret`.');
    for (const [section, list] of sections(keys)) {
        out.push('');
        out.push(`# ${'='.repeat(96)}`);
        out.push(`# ${titleOf(section)}`);
        out.push(`# ${'='.repeat(96)}`);
        for (const k of list) {
            out.push('');
            out.push(...wrap(k.desc || '', 100, '# '));
            const facts = [`Type: ${typeText(k)}.`];
            if (k.required) facts.unshift('REQUIRED.');
            if (takesFile(k)) facts.push(`Or ${k.name}_FILE=<path>.`);
            out.push(...wrap(facts.join(' '), 100, '# '));
            if (k.required) out.push(`${k.name}=`);
            else if (isSecret(k)) out.push(`# ${k.name}=`);
            else out.push(`# ${k.name}=${defaultText(k)}`);
        }
    }
    out.push('');
    return out.join('\n');
}

const md = (s) => String(s).replace(/\|/g, '\\|').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** @returns {string} the docs/CONFIG.md text */
export function renderConfigDoc(keys = CONFIG_KEYS) {
    const out = [];
    out.push('# Server configuration');
    out.push('');
    out.push('<!-- Generated by tools/gen-env-example.js from src/config.js: do not edit by hand, run `npm run gen:env`. -->');
    out.push('');
    out.push('The server reads its settings from environment variables and from an optional `.env` file');
    out.push('(`KEY=value` lines; `.env` next to `package.json`, or the file named by `SCACELITH_ENV_FILE`).');
    out.push('Environment variables take precedence over the file. A secret can also be given as a file with');
    out.push('the `_FILE` suffix (`SERVER_SECRET_FILE=/run/secrets/scacelith`), which keeps it out of the');
    out.push('process environment. `node bin/scacelith-server.js check-config` validates the configuration and');
    out.push('prints the effective values (secrets masked); `node bin/scacelith-server.js gen-secret` prints a');
    out.push('fresh random secret. `.env.example` lists every key with its default.');
    out.push('');
    out.push('Sections:');
    out.push('');
    const all = sections(keys);
    for (const s of all.keys()) out.push(`- [${titleOf(s)}](#${titleOf(s).toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/ /g, '-')})`);
    for (const [section, list] of all) {
        out.push('');
        out.push(`## ${titleOf(section)}`);
        out.push('');
        out.push('| Variable | Type | Default | Description |');
        out.push('| --- | --- | --- | --- |');
        for (const k of list) {
            let def;
            if (k.required) def = '**required**';
            else if (isSecret(k)) def = '(unset)';
            else def = defaultText(k) === '' ? '(empty)' : `\`${md(defaultText(k))}\``;
            const name = takesFile(k) ? `\`${k.name}\`<br>\`${k.name}_FILE\`` : `\`${k.name}\``;
            out.push(`| ${name} | ${md(typeText(k))} | ${def} | ${md(k.desc || '')} |`);
        }
    }
    out.push('');
    return out.join('\n');
}

function main(argv) {
    const check = argv.includes('--check');
    const files = [
        [path.join(ROOT, '.env.example'), renderEnvExample()],
        [path.join(ROOT, 'docs', 'CONFIG.md'), renderConfigDoc()],
    ];
    let stale = 0;
    for (const [file, text] of files) {
        let cur = null;
        try { cur = fs.readFileSync(file, 'utf8'); } catch { /* absent */ }
        if (cur === text) continue;
        if (check) { process.stderr.write(`${path.relative(ROOT, file)} is out of date: run npm run gen:env\n`); stale++; continue; }
        fs.mkdirSync(path.dirname(file), { recursive: true });
        fs.writeFileSync(file, text);
        process.stdout.write(`wrote ${path.relative(ROOT, file)}\n`);
    }
    if (stale) process.exitCode = 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));

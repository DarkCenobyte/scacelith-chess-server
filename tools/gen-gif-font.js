#!/usr/bin/env node
// Writes the bitmap fonts of the game GIFs (src/gif/font.js) to assets/fonts/scacelith-gif/:
// subsets of Terminus Font (Dimitar Toshkov Zhekov, SIL Open Font License 1.1) in BDF, with the
// characters the GIFs print (ASCII, plus a few signs: middle dot, one half, en dash, ellipsis,
// bullet). Terminus Font is a Reserved Font Name of the OFL, so the subsets carry their own name
// ("Scacelith GIF"). Changes from the original glyphs: the digit zero has no inner slash (the
// letter O's shape in that font). The OFL text is copied next to the fonts.
//
//   node tools/gen-gif-font.js <terminus-font-4.49.1 source folder>
//   (https://sourceforge.net/projects/terminus-font/, version 4.49.1)

import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { join } from 'node:path';

const SIZES = ['12n', '12b', '16n', '16b', '24n', '24b'];
const EXTRA = [0xb7, 0xbd, 0x2013, 0x2026, 0x2022];
const CODES = new Set([...Array.from({ length: 95 }, (_, i) => 32 + i), ...EXTRA]);

const src = process.argv[2];
if (!src) {
    console.error('usage: node tools/gen-gif-font.js <terminus-font source folder>');
    process.exit(2);
}
const outDir = new URL('../assets/fonts/scacelith-gif/', import.meta.url);
mkdirSync(outDir, { recursive: true });

for (const size of SIZES) {
    const text = readFileSync(join(src, `ter-u${size}.bdf`), 'latin1');
    const head = text.slice(0, text.indexOf('STARTCHAR'));
    const chars = [...text.matchAll(/STARTCHAR [^\n]*\n([\s\S]*?)ENDCHAR\n/g)];
    const byCode = new Map();
    for (const c of chars) {
        const enc = Number(/^ENCODING (\d+)$/m.exec(c[1])[1]);
        if (CODES.has(enc)) byCode.set(enc, c[1]);
    }
    for (const c of CODES) if (!byCode.has(c)) throw new Error(`${size}: no glyph U+${c.toString(16)}`);
    // Zero without its slash: the bitmap of the letter O.
    const bitmapOf = (body) => body.slice(body.indexOf('BITMAP\n'));
    byCode.set(0x30, byCode.get(0x30).replace(bitmapOf(byCode.get(0x30)), bitmapOf(byCode.get(0x4f))));

    const weight = size.endsWith('b') ? 'Bold' : 'Medium';
    const px = parseInt(size, 10);
    let h = head
        .replace(/^FONT .*$/m, (l) => l.replace('-xos4-Terminus-', '-scacelith-Scacelith GIF-'))
        .replace(/^FAMILY_NAME .*$/m, 'FAMILY_NAME "Scacelith GIF"')
        .replace(/^FOUNDRY .*$/m, 'FOUNDRY "scacelith"')
        .replace(/^COPYRIGHT .*$/m, 'COPYRIGHT "Copyright (C) 2020 Dimitar Toshkov Zhekov (Terminus Font)"')
        .replace(/^DEFAULT_CHAR .*$/m, 'DEFAULT_CHAR 63')
        .replace(/^CHARS .*$/m, `CHARS ${byCode.size}`);
    h = h.replace(/^STARTFONT 2\.1\n/, `STARTFONT 2.1\nCOMMENT Scacelith GIF ${px} px ${weight}: a subset of Terminus Font 4.49.1 by Dimitar Toshkov Zhekov,\n`
        + 'COMMENT modified (digit zero without slash), under the SIL Open Font License 1.1 (OFL.txt).\n'
        + 'COMMENT Generated by dedicated-server/tools/gen-gif-font.js.\n');
    let body = '';
    for (const c of [...byCode.keys()].sort((a, b) => a - b)) body += `STARTCHAR U+${c.toString(16).toUpperCase().padStart(4, '0')}\n${byCode.get(c)}ENDCHAR\n`;
    writeFileSync(new URL(`sg-${size}.bdf`, outDir), `${h}${body}ENDFONT\n`);
}
copyFileSync(join(src, 'OFL.TXT'), new URL('OFL.txt', outDir));
console.log(`wrote ${SIZES.length} fonts to ${outDir.pathname}`);
